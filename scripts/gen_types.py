#!/usr/bin/env python
"""Generate frontend TypeScript types from the backend Pydantic models.

  frontend/src/design/design.schema.json   + types.gen.ts      (the design document)
  frontend/src/contracts/contracts.schema.json + types.gen.ts  (clinical data contracts)

Run via `make types` after changing backend/app/models/*. With --check, exits 1
if the committed files are out of date (used by `make test`).
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
FRONTEND = ROOT / "frontend"

BANNER = ("/* eslint-disable */\n// GENERATED by scripts/gen_types.py from the backend "
          "Pydantic models. Do not edit.\n\n")


def schemas() -> dict[Path, dict]:
    from pydantic import BaseModel

    from app.models import clinical as c
    from app.models.design import Design

    class Contracts(BaseModel):
        """Wrapper so every data contract lands in one schema / one TS file."""

        patient: c.Patient
        patient_settings: c.PatientSettings
        oxygen: c.OxygenTherapy
        observation: c.Observation
        observation_set: c.ObservationSet
        lab_series: c.LabSeries
        imaging_study: c.ImagingStudy
        finding: c.Finding
        forecast_bundle: c.ForecastBundle
        alarm_state: c.AlarmState
        stream_message: c.StreamMessage

    return {
        # mode="serialization": fields with defaults are always present in what the
        # server sends (documents are stored fully populated), so the TS types have
        # required discriminators and no spurious `undefined`.
        FRONTEND / "src/design/design.schema.json":
            Design.model_json_schema(mode="serialization"),
        FRONTEND / "src/contracts/contracts.schema.json":
            Contracts.model_json_schema(mode="serialization"),
    }


def _strip_titles(node, keep: bool = False):
    """Drop per-property titles so json2ts emits inline types, not `Enabled1` aliases.
    Titles on the root and on each $defs entry are kept: they name the interfaces."""
    if isinstance(node, list):
        return [_strip_titles(x) for x in node]
    if not isinstance(node, dict):
        return node
    out = {}
    for k, v in node.items():
        if k == "title" and not keep and isinstance(v, str):
            continue
        if k == "$defs":
            out[k] = {name: _strip_titles(d, keep=True) for name, d in v.items()}
        elif k == "properties":
            out[k] = {name: _strip_titles(d) for name, d in v.items()}
        else:
            out[k] = _strip_titles(v)
    return out


def render(schema_path: Path) -> str:
    slim = schema_path.with_suffix(".slim.tmp.json")
    slim.write_text(json.dumps(_strip_titles(json.loads(schema_path.read_text()), keep=True)))
    try:
        return _json2ts(slim)
    finally:
        slim.unlink(missing_ok=True)


def _json2ts(schema_path: Path) -> str:
    out = subprocess.run(
        ["npx", "--no-install", "json2ts", "--input", str(schema_path),
         "--no-bannerComment", "--unreachableDefinitions", "--additionalProperties", "false"],
        cwd=FRONTEND, check=True, capture_output=True, text=True).stdout
    return BANNER + out


def main() -> int:
    check = "--check" in sys.argv
    stale: list[str] = []
    for schema_path, schema in schemas().items():
        text = json.dumps(schema, indent=2, sort_keys=True) + "\n"
        ts_path = schema_path.with_name("types.gen.ts")
        if check:
            if not schema_path.exists() or schema_path.read_text() != text:
                stale.append(str(schema_path.relative_to(ROOT)))
                continue
            if not ts_path.exists() or ts_path.read_text() != render(schema_path):
                stale.append(str(ts_path.relative_to(ROOT)))
            continue
        schema_path.write_text(text)
        ts_path.write_text(render(schema_path))
        print("wrote", ts_path.relative_to(ROOT))
    if stale:
        print("Out of date, run `make types`:", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
